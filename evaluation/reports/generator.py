"""Benchmark report generator producing Markdown, JSON, and CSV summaries."""

import csv
import io
import json
from dataclasses import asdict
from datetime import datetime
from typing import Any

from evaluation.metrics.engine import BenchmarkMetricsSummary
from evaluation.runners.batch_runner import BatchResult


class BenchmarkReportGenerator:
    """Generates human-readable Markdown and machine-readable JSON/CSV reports."""

    @classmethod
    def generate_markdown(
        cls,
        batch_result: BatchResult,
        run_title: str = "CodeGuard AI Benchmark Evaluation Report",
    ) -> str:
        """Construct human-readable Markdown benchmark report."""
        m = batch_result.summary_metrics

        lines = [
            f"# {run_title}",
            "",
            f"- **Run ID**: `{batch_result.run_id}`",
            f"- **Run Name**: `{batch_result.run_name}`",
            f"- **Dataset Version**: `{batch_result.dataset_version}`",
            f"- **Timestamp**: `{batch_result.completed_at.isoformat()}`",
            f"- **Total Duration**: `{batch_result.duration_seconds:.2f}s`",
            f"- **Scenarios Executed**: `{m.scenarios_total}` (Passed: `{m.scenarios_passed}`, Failed: `{m.scenarios_failed}`)",
            "",
            "## 1. Executive Performance Summary",
            "",
            "| Metric | Measured Value | Target / Ideal |",
            "| :--- | :--- | :--- |",
            f"| **Precision** | **{m.precision * 100:.1f}%** ({m.true_positives}/{m.true_positives + m.false_positives}) | > 85.0% |",
            f"| **Recall** | **{m.recall * 100:.1f}%** ({m.true_positives}/{m.true_positives + m.false_negatives}) | > 80.0% |",
            f"| **F1 Score** | **{m.f1:.4f}** | > 0.8200 |",
            f"| **True Positives (TP)** | `{m.true_positives}` | — |",
            f"| **False Positives (FP)** | `{m.false_positives}` | 0 |",
            f"| **False Negatives (FN)** | `{m.false_negatives}` | 0 |",
            f"| **Valid Line Accuracy** | `{m.valid_line_rate * 100:.1f}%` | 100.0% |",
            f"| **Exact Severity Accuracy** | `{m.exact_severity_rate * 100:.1f}%` | > 90.0% |",
            f"| **Category Accuracy** | `{m.category_accuracy_rate * 100:.1f}%` | > 90.0% |",
            f"| **P50 Latency** | `{m.p50_latency_ms:.1f}ms` | < 1500ms |",
            f"| **P95 Latency** | `{m.p95_latency_ms:.1f}ms` | < 5000ms |",
            f"| **Total Tokens Consumed** | `{m.total_tokens:,}` | — |",
            f"| **Estimated Cost** | `${m.estimated_cost_usd:.6f}` | — |",
            "",
            "## 2. Accuracy & Alignment Metrics",
            "",
            "| Dimension | Valid / Match | Over / Misaligned | Under / Error |",
            "| :--- | :--- | :--- | :--- |",
            f"| **Line Mapping** | Valid: `{m.valid_line_count}` ({m.valid_line_rate * 100:.1f}%) | Wrong File: `{m.wrong_file_count}` | Wrong Line: `{m.wrong_line_count}` |",
            f"| **Severity Audit** | Exact: `{m.exact_severity_count}` ({m.exact_severity_rate * 100:.1f}%) | Over-Severity: `{m.over_severity_count}` ({m.over_severity_rate * 100:.1f}%) | Under-Severity: `{m.under_severity_count}` ({m.under_severity_rate * 100:.1f}%) |",
            f"| **Category Match** | Exact/Compatible: `{m.category_match_count}` ({m.category_accuracy_rate * 100:.1f}%) | Mismatches: `{m.true_positives - m.category_match_count}` | — |",
            "",
            "## 3. Adversarial Judge & Verification Funnel",
            "",
            "| Verification Stage | Count | Description |",
            "| :--- | :--- | :--- |",
            f"| **Raw Candidates Before Judge** | `{m.judge_effectiveness.candidates_before_judge}` | Initial candidate findings generated by specialists |",
            f"| **Gate 1: Diff Boundary Rejection** | `{m.verification_funnel.gate1_diff_boundary_rejected}` | Rejected hallucinated line numbers without LLM call |",
            f"| **Gate 2: Factuality / Existing Guard Rejection** | `{m.verification_funnel.gate2_factuality_rejected}` | Suppressed false positives where caller enforces guard |",
            f"| **Gate 3: Actionability Rejection** | `{m.verification_funnel.gate3_actionability_rejected}` | Rejected vague or cosmetic suggestions |",
            f"| **Gate 4: Severity Downgrades** | `{m.verification_funnel.gate4_severity_downgraded}` | Calibrated severity inflation |",
            f"| **Gate 5: Execution Sandbox Rejections** | `{m.verification_funnel.gate5_execution_rejected}` | Failed behavioral or static checks |",
            f"| **Deduplicated Redundant Findings** | `{m.verification_funnel.deduplicated_count}` | Consolidated overlapping findings under shared root causes |",
            f"| **Final Publishable Findings** | `{m.final_findings_total}` | High-confidence, verified review findings |",
            f"| **Noise Reduction Rate** | `{m.judge_effectiveness.noise_reduction_rate * 100:.1f}%` | Percentage of false positives intercepted by Judge |",
            f"| **True Positive Retention Rate** | `{m.judge_effectiveness.tp_retention_rate * 100:.1f}%` | Percentage of valid defects retained through Judge |",
            "",
            "## 4. Agent-Level Telemetry Breakdown",
            "",
            "| Agent Name | Candidates | Tokens | Cost ($) | Avg Latency (ms) | Failures |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]

        for name, am in m.agent_metrics.items():
            avg_lat = round(am.total_latency_ms / am.calls_count, 1) if am.calls_count > 0 else 0.0
            lines.append(
                f"| `{name}` | `{am.candidates_count}` | `{am.total_tokens:,}` | `${am.estimated_cost:.6f}` | `{avg_lat}ms` | `{am.failures_count}` |"
            )

        lines.extend(
            [
                "",
                "## 5. Per-Scenario Execution Breakdown",
                "",
                "| Scenario ID | Status | Latency | Findings | TP | FP | FN | MCP Decision |",
                "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
            ]
        )

        for sc in batch_result.scenario_results:
            tp_cnt = len(sc.match_result.true_positives) if sc.match_result else 0
            fp_cnt = len(sc.match_result.false_positives) if sc.match_result else 0
            fn_cnt = len(sc.match_result.false_negatives) if sc.match_result else 0
            f_cnt = len(sc.final_findings)
            lines.append(
                f"| `{sc.scenario_id}` | `{sc.status}` | `{sc.latency_ms:.1f}ms` | `{f_cnt}` | `{tp_cnt}` | `{fp_cnt}` | `{fn_cnt}` | `{sc.mcp_policy_decision}` |"
            )

        lines.extend(
            [
                "",
                "---",
                "*(All metrics generated deterministically from actual benchmark runs. Zero fabricated metrics.)*",
            ]
        )

        return "\n".join(lines)

    @classmethod
    def generate_json(cls, batch_result: BatchResult) -> str:
        """Construct machine-readable JSON benchmark report."""
        data = {
            "run_id": batch_result.run_id,
            "run_name": batch_result.run_name,
            "dataset_version": batch_result.dataset_version,
            "started_at": batch_result.started_at.isoformat(),
            "completed_at": batch_result.completed_at.isoformat(),
            "duration_seconds": batch_result.duration_seconds,
            "concurrency": batch_result.concurrency,
            "metrics": batch_result.summary_metrics.to_dict(),
            "scenarios": [
                {
                    "scenario_id": sc.scenario_id,
                    "status": sc.status,
                    "latency_ms": sc.latency_ms,
                    "total_tokens": sc.total_tokens,
                    "estimated_cost": sc.estimated_cost,
                    "final_findings_count": len(sc.final_findings),
                    "true_positives_count": len(sc.match_result.true_positives) if sc.match_result else 0,
                    "false_positives_count": len(sc.match_result.false_positives) if sc.match_result else 0,
                    "false_negatives_count": len(sc.match_result.false_negatives) if sc.match_result else 0,
                    "mcp_policy_decision": sc.mcp_policy_decision,
                    "error_message": sc.error_message,
                }
                for sc in batch_result.scenario_results
            ],
            "failures": batch_result.failure_reasons,
        }
        return json.dumps(data, indent=2)

    @classmethod
    def generate_csv(cls, batch_result: BatchResult) -> str:
        """Construct tabular CSV benchmark report."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(
            [
                "scenario_id",
                "status",
                "latency_ms",
                "tokens",
                "cost_usd",
                "final_findings",
                "true_positives",
                "false_positives",
                "false_negatives",
                "mcp_decision",
                "error_message",
            ]
        )

        for sc in batch_result.scenario_results:
            tp_cnt = len(sc.match_result.true_positives) if sc.match_result else 0
            fp_cnt = len(sc.match_result.false_positives) if sc.match_result else 0
            fn_cnt = len(sc.match_result.false_negatives) if sc.match_result else 0
            writer.writerow(
                [
                    sc.scenario_id,
                    sc.status,
                    sc.latency_ms,
                    sc.total_tokens,
                    sc.estimated_cost,
                    len(sc.final_findings),
                    tp_cnt,
                    fp_cnt,
                    fn_cnt,
                    sc.mcp_policy_decision,
                    sc.error_message or "",
                ]
            )

        return output.getvalue()
